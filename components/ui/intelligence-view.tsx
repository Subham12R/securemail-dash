              <div>
                <span className="text-[11px] font-semibold uppercase tracking-wider text-zinc-400">
                  Risk Level
                </span>
                <div className="text-sm font-bold text-amber-500 mt-0.5">
                  {assessment.riskLevel}
                </div>
              </div>
              <div>
                <span className="text-[11px] font-semibold uppercase tracking-wider text-zinc-400">
                  Confidence
                </span>
