                    key={fIdx}
                    className="flex items-center gap-2 rounded-lg border border-zinc-100 bg-zinc-50 px-3.5 py-2 text-xs sm:text-sm text-zinc-800 dark-soc:border-[#1E2D56]/60 dark-soc:bg-[#0D1735]/70 dark-soc:text-zinc-200"
